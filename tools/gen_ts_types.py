"""Write TypeScript interfaces for the web UI's view models, so Vue pages are type-checked
against what the routes send (`just frontend-types`, part of the front end's build).

    uv run python -m tools.gen_ts_types webui/frontend/src/types/generated

Every dataclass defined in a `webui.service` module, and every dataclass they reach, becomes
an interface of its fields, typed as orjson sends them: tuples and lists as arrays, enums as
their values, dates as ISO text, `None` as `null`. A file per Python module
(`webui.service.info.ts`), so names need only be unique within one. Properties aren't sent,
so they aren't typed.
"""

import dataclasses
import datetime
import enum
import importlib
import pkgutil
import sys
import types
import typing
from collections.abc import Mapping, Sequence
from pathlib import Path

import click

PACKAGE = "webui.service"
HEADER = "// Generated by tools/gen_ts_types.py from webui/service's dataclasses: don't edit.\n"


def service_dataclasses() -> list[type]:
    package = importlib.import_module(PACKAGE)
    found = []

    for info in pkgutil.iter_modules(package.__path__):
        module = importlib.import_module(f"{PACKAGE}.{info.name}")
        found += [
            value
            for value in vars(module).values()
            if dataclasses.is_dataclass(value)
            and isinstance(value, type)
            and value.__module__ == module.__name__
        ]

    return found


def module_files(roots: list[type]) -> dict[str, str]:
    """Each dataclass reached from `roots` as an interface, in a file per Python module (its
    dotted name), importing the others it names."""
    modules: dict[str, dict[str, str]] = {}  # module -> class name -> interface
    imports: dict[str, set[type]] = {}
    pending = list(roots)

    while pending:
        cls = pending.pop(0)
        written = modules.setdefault(cls.__module__, {})

        if cls.__name__ in written:
            continue

        hints = typing.get_type_hints(cls)
        lines = []

        for field in dataclasses.fields(cls):
            text, reached = ts_type(hints[field.name])
            pending += reached
            imports.setdefault(cls.__module__, set()).update(
                other for other in reached if other.__module__ != cls.__module__
            )
            lines.append(f"  {field.name}: {text};")

        written[cls.__name__] = f"export interface {cls.__name__} {{\n" + "\n".join(lines) + "\n}\n"

    return {
        module: HEADER
        + import_lines(imports.get(module, set()))
        + "\n"
        + "\n".join(written.values())
        for module, written in modules.items()
    }


def import_lines(classes: set[type]) -> str:
    by_module: dict[str, list[str]] = {}

    for cls in classes:
        by_module.setdefault(cls.__module__, []).append(cls.__name__)

    return "".join(
        f'import type {{ {", ".join(sorted(names))} }} from "./{module}";\n'
        for module, names in sorted(by_module.items())
    )


def ts_type(hint: object) -> tuple[str, list[type]]:
    """The TypeScript for a type hint, and the dataclasses it names."""
    if typing.get_origin(hint) is not None:
        return generic_type(hint)

    match hint:
        case typing.TypeAliasType():
            return ts_type(hint.__value__)

        case type() if dataclasses.is_dataclass(hint):
            return hint.__name__, [hint]

        case type() if issubclass(hint, enum.Enum):
            return " | ".join(literal(member.value) for member in hint), []

        case type() if issubclass(hint, bool):
            return "boolean", []

        case type() if issubclass(hint, int | float):
            return "number", []

        case type() if issubclass(hint, str | datetime.date):
            return "string", []  # orjson sends dates and times as ISO text

        case None | types.NoneType:
            return "null", []

    print(f"untyped: {hint!r} sent as unknown", file=sys.stderr)
    return "unknown", []


def generic_type(hint: object) -> tuple[str, list[type]]:
    origin = typing.get_origin(hint)
    args = typing.get_args(hint)

    if origin is typing.Literal:
        return " | ".join(literal(arg) for arg in args), []

    if origin in (types.UnionType, typing.Union):
        return union(args)

    if origin is tuple and len(args) == 2 and args[1] is Ellipsis:
        return array(args[0])

    if origin is tuple:
        parts = [ts_type(arg) for arg in args]
        return "[" + ", ".join(text for text, _ in parts) + "]", flatten(parts)

    if isinstance(origin, type) and issubclass(origin, Mapping):
        text, reached = ts_type(args[1])
        return f"Record<string, {text}>", reached

    if isinstance(origin, type) and issubclass(origin, Sequence | set | frozenset):
        return array(args[0])

    print(f"unknown type: {hint!r} sent as unknown", file=sys.stderr)
    return "unknown", []


def union(args: tuple[object, ...]) -> tuple[str, list[type]]:
    parts = [ts_type(arg) for arg in args]
    return " | ".join(dict.fromkeys(text for text, _ in parts)), flatten(parts)


def array(item: object) -> tuple[str, list[type]]:
    text, reached = ts_type(item)
    return (f"({text})[]" if "|" in text else f"{text}[]"), reached


def flatten(parts: list[tuple[str, list[type]]]) -> list[type]:
    return [cls for _, reached in parts for cls in reached]


def literal(value: object) -> str:
    match value:
        case bool():
            return "true" if value else "false"

        case str():
            return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

    return str(value)


@click.command()
@click.argument("out", type=click.Path(file_okay=False, path_type=Path))
def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    files = {f"{module}.ts": text for module, text in module_files(service_dataclasses()).items()}

    for stale in set(path.name for path in out.glob("*.ts")) - set(files):
        out.joinpath(stale).unlink()

    for name, text in files.items():
        if (path := out / name).exists() and path.read_text() == text:
            continue

        path.write_text(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
